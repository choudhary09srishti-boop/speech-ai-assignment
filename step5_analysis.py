"""STEP 5 (CPU only, ~10 s) - Extra analysis from the saved CSVs.
Writes results/analysis.md : latency breakdown, bootstrap confidence intervals,
error analysis, and (if present) manual-review numbers."""
import os
import numpy as np
import pandas as pd
import config

R = config.RESULTS_DIR
conds = config.CONDITIONS
asr = {c: pd.read_csv(f"{R}/asr_{c}.csv").sort_values("id").reset_index(drop=True) for c in conds}
llm = {c: pd.read_csv(f"{R}/llm_{c}.csv").sort_values("id").reset_index(drop=True) for c in conds}
out = ["# Extra analysis (auto-generated by step5_analysis.py)\n"]

# 1. Latency breakdown
out.append("## 1. Latency breakdown (mean seconds per clip)\n")
out.append("| condition | denoise | ASR | LLM | total | LLM share |\n|---|---|---|---|---|---|")
for c in conds:
    d, a, l = asr[c].denoise_sec.mean(), asr[c].asr_sec.mean(), llm[c].llm_sec.mean()
    t = d + a + l
    out.append(f"| {c} | {d:.2f} | {a:.2f} | {l:.2f} | {t:.2f} | {l/t:.0%} |")

# 2. Paired bootstrap on corpus WER
def boot(a, b, n=2000, seed=0):
    rng = np.random.default_rng(seed)
    N = len(a); diffs = []
    for _ in range(n):
        i = rng.integers(0, N, N)
        wa = a.word_errors.values[i].sum() / a.word_total.values[i].sum()
        wb = b.word_errors.values[i].sum() / b.word_total.values[i].sum()
        diffs.append(wb - wa)
    return np.mean(diffs), np.percentile(diffs, 2.5), np.percentile(diffs, 97.5)

out.append("\n## 2. Paired bootstrap of WER difference (2000 resamples, 95% CI)\n")
out.append("| comparison | mean WER diff | 95% CI | significant? |\n|---|---|---|---|")
for a, b in [("clean", "noisy"), ("noisy", "noisy_denoised"), ("clean", "noisy_denoised")]:
    m, lo, hi = boot(asr[a], asr[b])
    out.append(f"| {b} - {a} | {m:+.3f} | [{lo:+.3f}, {hi:+.3f}] | {'yes' if lo > 0 or hi < 0 else 'no'} |")
out.append("\nA positive difference means the second condition has HIGHER (worse) WER.")

# 3. Error analysis
c = asr["clean"].merge(llm["clean"][["id", "response_f1", "hallucination"]], on="id")
def rank_corr(x, y):
    return float(np.corrcoef(pd.Series(x).rank(), pd.Series(y).rank())[0, 1])
out.append("\n## 3. Error analysis (clean condition)\n")
out.append(f"- Spearman(clip duration, WER) = {rank_corr(c.audio_sec, c.wer):+.2f}")
out.append(f"- Spearman(WER, response F1) = {rank_corr(c.wer, c.response_f1):+.2f}")
out.append(f"- Mean response F1 when WER <= 0.4: {c[c.wer <= 0.4].response_f1.mean():.3f}  (n={(c.wer <= 0.4).sum()})")
out.append(f"- Mean response F1 when WER > 0.4: {c[c.wer > 0.4].response_f1.mean():.3f}  (n={(c.wer > 0.4).sum()})")
out.append(f"- Hallucination rate when WER <= 0.4: {c[c.wer <= 0.4].hallucination.mean():.2f}; when WER > 0.4: {c[c.wer > 0.4].hallucination.mean():.2f}")
out.append("\nFive worst clips by WER (clean):\n")
for _, r in c.sort_values("wer", ascending=False).head(5).iterrows():
    out.append(f"- id {r.id}, WER {r.wer:.2f}\n  - REF: {r.reference}\n  - HYP: {r.hypothesis}")

# 4. Manual review
mf = os.path.join(R, "manual_review_filled.csv")
if os.path.exists(mf):
    m = pd.read_csv(mf)
    mc, mh = "manual_correct_0_or_1", "manual_hallucination_0_or_1"
    m = m.dropna(subset=[mc, mh])
    m = m.merge(llm["clean"][["id","hallucination"]].rename(columns={"hallucination":"auto_flag"}), on="id", how="left")
    out.append(f"\n## 4. Manual review (n={len(m)})\n")
    out.append(f"- Manual correctness rate: {m[mc].mean():.2%}")
    out.append(f"- Manual hallucination rate: {m[mh].mean():.2%}")
    out.append(f"- Automatic hallucination flag rate on the same rows: {m.auto_flag.astype(int).mean():.2%}")
    out.append(f"- Agreement between automatic flag and manual label: {(m.auto_flag.astype(int) == m[mh].astype(int)).mean():.2%}")
else:
    out.append("\n## 4. Manual review\nFile results/manual_review_filled.csv not found yet.")

open(f"{R}/analysis.md", "w", encoding="utf-8").write("\n".join(out))
print("\n".join(out))
